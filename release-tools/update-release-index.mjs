import { createHash } from 'node:crypto'
import { createReadStream } from 'node:fs'
import { access, readFile, readdir, rename, stat, writeFile } from 'node:fs/promises'
import { constants } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const workRoot = resolve(process.argv[2] || resolve(projectRoot, '..'))
const releasesRoot = resolve(workRoot, 'releases')

async function exists(path) {
  try {
    await access(path, constants.F_OK)
    return true
  } catch {
    return false
  }
}

function forwardSlashes(path) {
  return path.replaceAll('\\', '/')
}

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`
  if (bytes < 1024 ** 2) return `${(bytes / 1024).toFixed(1)} KiB`
  if (bytes < 1024 ** 3) return `${(bytes / 1024 ** 2).toFixed(1)} MiB`
  return `${(bytes / 1024 ** 3).toFixed(2)} GiB`
}

async function sha256(path) {
  const hash = createHash('sha256')
  for await (const chunk of createReadStream(path)) hash.update(chunk)
  return hash.digest('hex')
}

async function directoryStats(path) {
  let bytes = 0
  let files = 0
  const entries = await readdir(path, { withFileTypes: true })
  for (const entry of entries) {
    const entryPath = resolve(path, entry.name)
    if (entry.isDirectory()) {
      const nested = await directoryStats(entryPath)
      bytes += nested.bytes
      files += nested.files
    } else if (entry.isFile()) {
      bytes += (await stat(entryPath)).size
      files += 1
    }
  }
  return { bytes, files }
}

async function readCompanionStatus(zipPath, digest) {
  const companionPath = `${zipPath}.sha256.txt`
  if (!await exists(companionPath)) return { path: null, status: 'missing' }
  const content = await readFile(companionPath, 'utf8')
  const declared = content.match(/[a-f0-9]{64}/i)?.[0]?.toLowerCase() ?? null
  return {
    path: forwardSlashes(relative(releasesRoot, companionPath)),
    status: declared === digest ? 'match' : 'mismatch',
  }
}

async function atomicWrite(path, content) {
  const temporaryPath = `${path}.tmp`
  await writeFile(temporaryPath, content, 'utf8')
  await rename(temporaryPath, path)
}

if (!await exists(releasesRoot)) {
  throw new Error(`Release directory does not exist: ${releasesRoot}`)
}

const versionEntries = (await readdir(releasesRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && /^v\d+\.\d+\.\d+(?:[-+].+)?$/i.test(entry.name))
  .sort((left, right) => left.name.localeCompare(right.name, 'en', { numeric: true }))

const versions = []
const checksumLines = []

for (const versionEntry of versionEntries) {
  const versionRoot = resolve(releasesRoot, versionEntry.name)
  const artifactsRoot = resolve(versionRoot, 'artifacts')
  const extractedRoot = resolve(versionRoot, 'extracted')
  const archives = []
  const extracted = []

  if (await exists(artifactsRoot)) {
    const artifactEntries = (await readdir(artifactsRoot, { withFileTypes: true }))
      .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.zip'))
      .sort((left, right) => left.name.localeCompare(right.name, 'en', { numeric: true }))

    for (const entry of artifactEntries) {
      const path = resolve(artifactsRoot, entry.name)
      const digest = await sha256(path)
      const metadata = await stat(path)
      const relativePath = forwardSlashes(relative(releasesRoot, path))
      const companion = await readCompanionStatus(path, digest)
      archives.push({
        name: entry.name,
        path: relativePath,
        bytes: metadata.size,
        sha256: digest,
        companion,
      })
      checksumLines.push(`${digest} *${relativePath}`)
    }
  }

  if (await exists(extractedRoot)) {
    const extractedEntries = (await readdir(extractedRoot, { withFileTypes: true }))
      .filter((entry) => entry.isDirectory())
      .sort((left, right) => left.name.localeCompare(right.name, 'en', { numeric: true }))

    for (const entry of extractedEntries) {
      const path = resolve(extractedRoot, entry.name)
      const totals = await directoryStats(path)
      extracted.push({
        name: entry.name,
        path: forwardSlashes(relative(releasesRoot, path)),
        ...totals,
      })
    }
  }

  versions.push({ version: versionEntry.name, archives, extracted })
}

const generatedAt = new Date().toISOString()
const index = {
  product: 'HYPERION',
  generatedAt,
  releasesRoot: releasesRoot,
  versions,
}

const markdown = [
  '# HYPERION Release Index',
  '',
  `Generated: ${generatedAt}`,
  '',
  'This file is generated by `npm run release:index`. Do not edit it by hand.',
  '',
]

for (const version of versions) {
  markdown.push(`## ${version.version}`, '')
  if (version.archives.length) {
    markdown.push('| Archive | Size | SHA-256 | Companion |', '| --- | ---: | --- | --- |')
    for (const archive of version.archives) {
      markdown.push(`| \`${archive.name}\` | ${formatBytes(archive.bytes)} | \`${archive.sha256}\` | ${archive.companion.status} |`)
    }
    markdown.push('')
  } else {
    markdown.push('No ZIP archives.', '')
  }

  if (version.extracted.length) {
    markdown.push('| Extracted directory | Files | Size |', '| --- | ---: | ---: |')
    for (const directory of version.extracted) {
      markdown.push(`| \`${directory.name}\` | ${directory.files} | ${formatBytes(directory.bytes)} |`)
    }
    markdown.push('')
  }
}

await atomicWrite(resolve(releasesRoot, 'INDEX.json'), `${JSON.stringify(index, null, 2)}\n`)
await atomicWrite(resolve(releasesRoot, 'INDEX.md'), `${markdown.join('\n')}\n`)
await atomicWrite(resolve(releasesRoot, 'SHA256SUMS.txt'), `${checksumLines.join('\n')}\n`)

console.log(`Indexed ${versions.length} HYPERION versions in ${releasesRoot}`)
